function evidenceFor(finding: Finding, evidence: readonly Evidence[]): Evidence | undefined {
  return evidence.find((item) => finding.evidence_ids.includes(item.id));
}

export function findingText(
  finding: Finding,
  locale: Locale,
  evidence: readonly Evidence[] = [],
  subject?: string,
): { title: string; description: string } {
  if (locale === "en") return { title: finding.title, description: finding.description };

  const field = subject ?? finding.subject ?? "—";
  const item = evidenceFor(finding, evidence);
  const count = typeof item?.observed_value === "number" ? item.observed_value.toLocaleString("es-ES") : null;
  const governanceTitles: Record<string, string> = {
    "GOV-ID-001": "Identificador inferido",
    "GOV-TEMP-001": "Campo temporal inferido",
    "GOV-CONTACT-001": "Información de contacto inferida",
    "GOV-GEO-001": "Información geográfica inferida",
    "GOV-DEMO-001": "Información demográfica inferida",
    "GOV-FIN-001": "Información financiera inferida",
    "GOV-METRIC-001": "Métrica de negocio inferida",
    "GOV-TEXT-001": "Texto libre inferido",
    "GOV-CAT-001": "Dimensión categórica inferida",
    "GOV-PERSONAL-001": "Posibles datos personales inferidos",
    "GOV-QUASI-001": "Posible cuasi-identificador inferido",
  };
  if (governanceTitles[finding.method]) {
    return {
      title: governanceTitles[finding.method],
      description: `La columna ${field} coincide con señales deterministas de gobernanza; no es una determinación legal ni de cumplimiento.`,
    };
  }

  switch (finding.method) {
    case "quality_validity_parser_v0_1":
      return {
        title: "Valores no nulos no superaron un analizador estructural",
        description: count
          ? `${count} valores no nulos de ${field} no superaron el analizador estructural esperado.`
          : `Algunos valores no nulos de ${field} no superaron el analizador estructural esperado.`,
      };
    case "QUALITY-IDENTIFIER-DUPLICATE-001":
      return {
        title: "Exceso de duplicados en un identificador candidato estructural",
        description: count
          ? `${count} filas duplicadas adicionales afectan al identificador candidato estructural ${field}.`
          : `Se detectaron filas duplicadas adicionales en el identificador candidato estructural ${field}.`,
      };
    case "QUALITY-IDENTIFIER-MISSING-001":
      return {
        title: "Valores ausentes en un identificador candidato estructural",
        description: count
          ? `${count} valores ausentes afectan al identificador candidato estructural ${field}.`
          : `Se detectaron valores ausentes en el identificador candidato estructural ${field}.`,
      };
    case "complete_row_duplicates_v0_1":
      return { title: "Se detectaron filas duplicadas completas", description: count ? `${count} filas duplicadas adicionales coinciden en todas las columnas.` : "Se detectaron filas duplicadas adicionales que coinciden en todas las columnas." };
    case "all_null_v0_1":
      return { title: "La columna solo contiene valores nulos", description: `La columna ${field} no contiene valores no nulos.` };
    case "constant_column_v0_1":
      return { title: "La columna tiene un único valor no nulo distinto", description: `La columna ${field} es constante entre sus valores no nulos.` };
    case "candidate_identifier_v0_1":
      return { title: "Identificador candidato estructural inferido", description: `La columna ${field} cumple las reglas estructurales de candidatura; no es una clave primaria confirmada ni un identificador semántico.` };
    default:
      return { title: finding.title, description: finding.description };
  }
}

export function recommendationText(
  recommendation: Recommendation,
  locale: Locale,
  finding?: Finding,
  evidence: readonly Evidence[] = [],
): { action: string; rationale: string } {
  if (locale === "en") return { action: recommendation.action, rationale: recommendation.rationale };
  const item = finding ? evidenceFor(finding, evidence) : undefined;
  const count = typeof item?.observed_value === "number" ? item.observed_value.toLocaleString("es-ES") : null;
  switch (recommendation.rule_id) {
    case "REC-QUALITY-DUPLICATE-ID-001":
      return {
        action: "Revisa y resuelve los valores duplicados de la columna identificadora candidata estructural antes de usarla para identificar registros de forma única.",
        rationale: count
          ? `El hallazgo de Calidad detectó de forma determinista ${count} filas duplicadas adicionales; se sugiere revisarlas antes de confiar en la identidad estructural.`
          : "El hallazgo de Calidad detectó filas duplicadas adicionales de forma determinista; se sugiere revisarlas antes de confiar en la identidad estructural.",
      };
    case "REC-QUALITY-MALFORMED-001":
      return {
        action: "Valida y corrige los valores mal formados frente al formato primitivo esperado detectado antes de su uso posterior.",
        rationale: "El hallazgo de Calidad detectó valores que no superaron el analizador estructural esperado; se sugiere validarlos sin añadir una regla de negocio.",
      };
    case "REC-GOV-PERSONAL-001":
      return {
        action: "Revisa y documenta el tratamiento previsto, la responsabilidad y las expectativas de conservación de los campos inferidos como posibles datos personales.",
        rationale: "El hallazgo de Gobernanza contiene señales deterministas compatibles con posibles datos personales; se sugiere revisar la documentación, sin constituir una conclusión legal.",
      };
    case "REC-GOV-QUASI-001":
      return {
        action: "Revisa si esta combinación de campos necesita documentación adicional de gobernanza antes de compartirla o reutilizarla más ampliamente.",
        rationale: "El hallazgo de Gobernanza clasifica una posible combinación cuasi-identificadora; se sugiere revisarla sin afirmar un riesgo de reidentificación.",
      };
    default:
      return { action: recommendation.action, rationale: recommendation.rationale };
  }
}

